$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) {
    throw "找不到 .NET Framework C# 编译器：$csc"
}

$srcDir = Join-Path $root 'src'
$assets = Join-Path $root 'assets'
$dist = Join-Path $root 'dist'
New-Item -ItemType Directory -Force -Path $dist | Out-Null

$versionFile = Join-Path $root 'version.txt'
if (-not (Test-Path $versionFile)) {
    throw "缺少 version.txt（版本号唯一来源）。"
}
$version = (Get-Content $versionFile -Raw).Trim()
$versionMatch = [regex]::Match($version, '^(\d+\.\d+\.\d+)(-[0-9A-Za-z.-]+)?$')
if (-not $versionMatch.Success) {
    throw "version.txt 必须是 x.y.z 或 x.y.z-pre 格式，当前为：$version"
}
$numericVersion = $versionMatch.Groups[1].Value
$assemblyVersion = "$numericVersion.0"
$appVersionSource = @"
// <auto-generated>由 build.ps1 根据 version.txt 生成，请勿手改。</auto-generated>
namespace CursorComet
{
    internal static class VersionInfo
    {
        public const string Version = "$version";
        public const string AssemblyVersion = "$assemblyVersion";
        public const string FileVersion = "$assemblyVersion";
    }
}
"@
[System.IO.File]::WriteAllText((Join-Path $srcDir 'VersionInfo.cs'), $appVersionSource, (New-Object System.Text.UTF8Encoding($false)))

$sources = @(Get-ChildItem -Path $srcDir -Filter *.cs | ForEach-Object { $_.FullName })
if ($sources.Count -eq 0) {
    throw "src 目录里没有 .cs 文件。"
}

$exePath = Join-Path $dist 'cursor-comet.exe'
$cscArgs = @(
    '/nologo',
    '/target:winexe',
    '/platform:anycpu',
    '/optimize+',
    '/codepage:65001',
    '/utf8output',
    '/reference:System.dll',
    '/reference:System.Drawing.dll',
    '/reference:System.Windows.Forms.dll',
    "/out:$exePath"
)
$icon = Join-Path $assets 'app.ico'
if (Test-Path $icon) {
    $cscArgs += "/win32icon:$icon"
}
$manifest = Join-Path $assets 'app.manifest'
if (Test-Path $manifest) {
    $cscArgs += "/win32manifest:$manifest"
}
$cscArgs += $sources

& $csc $cscArgs
if ($LASTEXITCODE -ne 0) {
    throw "编译失败，退出码 $LASTEXITCODE"
}

# 额外输出一份中文文件名，方便中文用户；主程序名固定为 cursor-comet.exe。
$artifact = $exePath
$alias = Join-Path $dist '鼠标拖尾.exe'
Copy-Item $exePath $alias -Force
Remove-Item (Join-Path $dist 'uninstall.exe') -Force -ErrorAction SilentlyContinue

Write-Host ''
Write-Host "编译完成：$exePath"
Write-Host "发布文件：$artifact"

$isccCandidates = @(
    (Join-Path $env:LOCALAPPDATA 'Programs\Inno Setup 6\ISCC.exe'),
    (Join-Path ${env:ProgramFiles(x86)} 'Inno Setup 6\ISCC.exe'),
    (Join-Path $env:ProgramFiles 'Inno Setup 6\ISCC.exe')
)
$iscc = $isccCandidates | Where-Object { $_ -and (Test-Path $_) } | Select-Object -First 1
if (-not $iscc) {
    $cmd = Get-Command iscc.exe -ErrorAction SilentlyContinue
    if ($cmd) {
        $iscc = $cmd.Source
    }
}
if (-not $iscc) {
    throw "未找到 Inno Setup 6 的 ISCC.exe。请先安装 Inno Setup 6：https://jrsoftware.org/isdl.php"
}

$iss = Join-Path $root 'installer\CursorComet.iss'
& $iscc "/DMyAppVersion=$version" "/DMyAppNumericVersion=$numericVersion" $iss
if ($LASTEXITCODE -ne 0) {
    throw "安装器编译失败，退出码 $LASTEXITCODE"
}

$setupPath = Join-Path $dist 'CursorComet-Setup.exe'
if (-not (Test-Path $setupPath)) {
    throw "安装器未生成：$setupPath"
}
Write-Host "安装包：$setupPath"

$sha = @(
    ((Get-FileHash $artifact -Algorithm SHA256).Hash.ToLower() + "  cursor-comet.exe"),
    ((Get-FileHash $setupPath -Algorithm SHA256).Hash.ToLower() + "  CursorComet-Setup.exe")
)
$sha | Set-Content -Path (Join-Path $dist 'SHA256SUMS.txt') -Encoding ASCII
Write-Host "校验：$(Join-Path $dist 'SHA256SUMS.txt')"
