$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) {
    throw "找不到 .NET Framework C# 编译器：$csc"
}

$srcDir = Join-Path $root 'src'
$assets = Join-Path $root 'assets'
$dist = Join-Path $root 'dist'
New-Item -ItemType Directory -Force -Path $dist | Out-Null

$versionFile = Join-Path $root 'version.txt'
if (-not (Test-Path $versionFile)) {
    throw "缺少 version.txt（版本号唯一来源）。"
}
$version = (Get-Content $versionFile -Raw).Trim()
if ($version -notmatch '^\d+\.\d+\.\d+$') {
    throw "version.txt 必须是 x.y.z 格式，当前为：$version"
}
$assemblyVersion = "$version.0"
$appVersionSource = @"
// <auto-generated>由 build.ps1 根据 version.txt 生成，请勿手改。</auto-generated>
namespace MouseTrail
{
    internal static class VersionInfo
    {
        public const string Version = "$version";
        public const string AssemblyVersion = "$assemblyVersion";
        public const string FileVersion = "$assemblyVersion";
    }
}
"@
[System.IO.File]::WriteAllText((Join-Path $srcDir 'VersionInfo.cs'), $appVersionSource, (New-Object System.Text.UTF8Encoding($false)))

$installerDir = Join-Path $root 'installer'
$installerVersionSource = @"
// <auto-generated>由 build.ps1 根据 version.txt 生成，请勿手改。</auto-generated>
namespace CursorCometSetup
{
    internal static class VersionInfo
    {
        public const string Version = "$version";
        public const string AssemblyVersion = "$assemblyVersion";
        public const string FileVersion = "$assemblyVersion";
    }
}
"@
[System.IO.File]::WriteAllText((Join-Path $installerDir 'VersionInfo.cs'), $installerVersionSource, (New-Object System.Text.UTF8Encoding($false)))

$sources = @(Get-ChildItem -Path $srcDir -Filter *.cs | ForEach-Object { $_.FullName })
if ($sources.Count -eq 0) {
    throw "src 目录里没有 .cs 文件。"
}

$exePath = Join-Path $dist '鼠标拖尾.exe'

$cscArgs = @(
    '/nologo',
    '/target:winexe',
    '/platform:anycpu',
    '/optimize+',
    '/codepage:65001',
    '/utf8output',
    '/reference:System.dll',
    '/reference:System.Drawing.dll',
    '/reference:System.Windows.Forms.dll',
    "/out:$exePath"
)

$icon = Join-Path $assets 'app.ico'
if (Test-Path $icon) {
    $cscArgs += "/win32icon:$icon"
}
$manifest = Join-Path $assets 'app.manifest'
if (Test-Path $manifest) {
    $cscArgs += "/win32manifest:$manifest"
}

$cscArgs += $sources

& $csc $cscArgs
if ($LASTEXITCODE -ne 0) {
    throw "编译失败，退出码 $LASTEXITCODE"
}

# 额外输出一份 ASCII 文件名，方便 CI/Release 使用，避免中文路径在 runner 上出问题。
$artifact = Join-Path $dist 'cursor-comet.exe'
Copy-Item $exePath $artifact -Force

Write-Host ''
Write-Host "编译完成：$exePath"
Write-Host "发布文件：$artifact"

$commonSource = Join-Path $root 'installer\Common.cs'
$uninstallerSource = Join-Path $root 'installer\Uninstaller.cs'
$uninstallerPath = Join-Path $dist 'uninstall.exe'
if ((Test-Path $commonSource) -and (Test-Path $uninstallerSource)) {
    $uninstallerArgs = @(
        '/nologo',
        '/target:winexe',
        '/platform:anycpu',
        '/optimize+',
        '/codepage:65001',
        '/utf8output',
        '/reference:System.dll',
        '/reference:System.Drawing.dll',
        '/reference:System.Windows.Forms.dll',
        "/out:$uninstallerPath"
    )
    if (Test-Path $icon) {
        $uninstallerArgs += "/win32icon:$icon"
    }
    if (Test-Path $manifest) {
        $uninstallerArgs += "/win32manifest:$manifest"
    }
    $uninstallerArgs += $commonSource
    $uninstallerArgs += (Join-Path $root 'installer\VersionInfo.cs')
    $uninstallerArgs += $uninstallerSource

    & $csc $uninstallerArgs
    if ($LASTEXITCODE -ne 0) {
        throw "卸载器编译失败，退出码 $LASTEXITCODE"
    }
    Write-Host "卸载器：$uninstallerPath"
}

# 编译安装器，把便携版 exe 和独立卸载器都嵌进去。
$setupSource = Join-Path $root 'installer\Setup.cs'
if ((Test-Path $commonSource) -and (Test-Path $setupSource) -and (Test-Path $uninstallerPath)) {
    $setupPath = Join-Path $dist 'CursorComet-Setup.exe'
    $setupArgs = @(
        '/nologo',
        '/target:winexe',
        '/platform:anycpu',
        '/optimize+',
        '/codepage:65001',
        '/utf8output',
        '/reference:System.dll',
        '/reference:System.Drawing.dll',
        '/reference:System.Windows.Forms.dll',
        "/resource:$artifact,CursorCometApp.exe",
        "/resource:$uninstallerPath,CursorCometUninstall.exe",
        "/out:$setupPath"
    )
    if (Test-Path $icon) {
        $setupArgs += "/win32icon:$icon"
    }
    if (Test-Path $manifest) {
        $setupArgs += "/win32manifest:$manifest"
    }
    $setupArgs += $commonSource
    $setupArgs += (Join-Path $root 'installer\VersionInfo.cs')
    $setupArgs += $setupSource

    & $csc $setupArgs
    if ($LASTEXITCODE -ne 0) {
        throw "安装器编译失败，退出码 $LASTEXITCODE"
    }
    Write-Host "安装包：$setupPath"
}
